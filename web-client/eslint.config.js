import js from '@eslint/js';
import * as astroParser from 'astro-eslint-parser';
import tseslint from 'typescript-eslint';

/**
 * AD-1 as a rule rather than a convention.
 *
 * `src/api/server.ts` (server-only, holds the bearer) and `src/api/client.ts` (browser,
 * bound to `/api`) are the only modules allowed to call `fetch`. Islands, stores and
 * components are the code that ships to the browser, so for them `fetch` and any route to
 * the server module are errors. `tests/unit/lint.test.ts` proves both fire.
 *
 * `.astro` files are parsed by `astro-eslint-parser` alone: `eslint-plugin-astro` would
 * pull in `eslint-plugin-jsx-a11y`, which does not support eslint 10, and the two rules
 * below are core eslint rules that need no plugin to work.
 */

const BROWSER_SIDE = ['src/islands/**', 'src/stores/**', 'src/components/**'];

const NO_DIRECT_BACKEND_CALL =
  'AD-1: the browser talks only to web-client. Call the proxy through `src/api/client.ts`.';

const NO_SERVER_MODULE =
  'AD-1: the credential lives in `src/api/server.ts`, which the browser must never load. ' +
  'Fetch through `src/api/client.ts`, or move the call into a page or an Action.';

const restrictions = {
  'no-restricted-globals': ['error', { name: 'fetch', message: NO_DIRECT_BACKEND_CALL }],
  'no-restricted-imports': [
    'error',
    {
      paths: [
        { name: 'astro:env/server', message: NO_SERVER_MODULE },
        { name: 'astro:env', message: NO_SERVER_MODULE },
      ],
      patterns: [{ regex: '(^|/)api/server(\\.ts)?$', message: NO_SERVER_MODULE }],
    },
  ],
};

export default tseslint.config(
  {
    ignores: [
      'dist/**',
      '.astro/**',
      'node_modules/**',
      'test-results/**',
      'playwright-report/**',
      // written by `pnpm test --coverage`
      'coverage/**',
      // generated by `pnpm gen:api`; the drift check in `make lint` is its gate (AD-3)
      'src/api/schema.d.ts',
    ],
  },
  js.configs.recommended,
  tseslint.configs.recommended,
  {
    files: ['**/*.astro'],
    languageOptions: {
      parser: astroParser,
      parserOptions: { parser: tseslint.parser, extraFileExtensions: ['.astro'] },
    },
  },
  {
    // Node scripts and the e2e stub server. Only the globals they actually use are
    // declared, rather than pulling in a globals package to say the same thing.
    files: ['**/*.mjs', '**/*.js'],
    languageOptions: { globals: { process: 'readonly', URL: 'readonly', console: 'readonly' } },
  },
  {
    files: BROWSER_SIDE.flatMap((base) => [`${base}/*.ts`, `${base}/*.tsx`, `${base}/*.astro`]),
    rules: restrictions,
  },
);
