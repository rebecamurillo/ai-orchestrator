/**
 * Generate `src/api/schema.d.ts` from the exported contract, or prove it is current.
 *
 * AD-3: backend-api owns the contract. `make openapi` exports `contracts/openapi.json`
 * and then runs this with no arguments; `make lint` runs it with `--check`, which
 * regenerates into memory and compares, so a hand edit to the committed file — or a
 * backend schema change nobody regenerated — fails the gate by name.
 *
 * `--check` never writes to `src/api/schema.d.ts`: a check that repairs what it is
 * checking reports success on the run that should have failed.
 *
 * Usage: `node scripts/gen-api.mjs [--check] [--contract PATH] [--output PATH]`. The two
 * path flags default to the committed locations and exist so that `tests/unit/gen-api.test.ts`
 * can drive the drift gate against a scratch file instead of the repository's own.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const argv = process.argv.slice(2);

function flag(name, fallback) {
  const at = argv.indexOf(name);
  return at === -1 ? fallback : resolve(argv[at + 1]);
}

const CONTRACT = flag('--contract', resolve(PACKAGE_ROOT, '..', 'contracts', 'openapi.json'));
const TARGET = flag('--output', resolve(PACKAGE_ROOT, 'src', 'api', 'schema.d.ts'));
const TARGET_LABEL = relative(PACKAGE_ROOT, TARGET);

/** Marks the file as machine-written, so nobody reaches for it as a place to add a type. */
const BANNER = [
  '// GENERATED by `pnpm gen:api` from contracts/openapi.json — do not edit (AD-3).',
  '// The contract is owned by backend-api. Change a Pydantic schema, then run `make openapi`.',
  '',
].join('\n');

function generate() {
  const generated = execFileSync(
    process.execPath,
    [resolve(PACKAGE_ROOT, 'node_modules', 'openapi-typescript', 'bin', 'cli.js'), CONTRACT],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  );
  return BANNER + generated;
}

function read() {
  try {
    return readFileSync(TARGET, 'utf8');
  } catch {
    return null;
  }
}

const check = argv.includes('--check');
const wanted = generate();

if (!check) {
  writeFileSync(TARGET, wanted);
  process.stdout.write(`gen:api: wrote ${TARGET_LABEL}\n`);
  process.exit(0);
}

const found = read();
if (found === wanted) {
  process.stdout.write(`gen:api: ${TARGET_LABEL} matches contracts/openapi.json\n`);
  process.exit(0);
}

process.stderr.write(
  `${TARGET_LABEL}: out of date with contracts/openapi.json.\n` +
    `${TARGET_LABEL} is generated (AD-3) and must never be hand-edited.\n` +
    'Run `make openapi` and commit the result.\n',
);
process.exit(1);
